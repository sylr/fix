package cancelorder

import (
	"fmt"
	"io"
	"slices"
	"time"

	"github.com/google/uuid"
	"github.com/rs/zerolog"
	"github.com/spf13/cobra"
	"github.com/sylr/fix2/fix"
	"github.com/sylr/fix2/fix/dictionary"

	"sylr.dev/fix/v2/cli/complete"
	"sylr.dev/fix/v2/cli/options"
	"sylr.dev/fix/v2/config"
	"sylr.dev/fix/v2/errors"
	"sylr.dev/fix/v2/fix50sp2"
	"sylr.dev/fix/v2/initiator"
	"sylr.dev/fix/v2/utils"
)

var (
	optionOrderSide          string
	optionOrderSymbol        string
	optionOrderID            string
	optionClientOrderID      string
	optionOrigClientOrderID  string
	optionExecReportsTimeout time.Duration
	partyIDOptions           *options.PartyIDOptions
)

var CancelOrderCmd = &cobra.Command{
	Use:               "order",
	Short:             "Cancel single order",
	Long:              "Send an order cancel request after initiating a session with a FIX acceptor, and wait for the order to be canceled.",
	Args:              cobra.ExactArgs(0),
	ValidArgsFunction: cobra.NoFileCompletions,
	PersistentPreRunE: Validate,
	RunE:              Execute,
}

func init() {
	flags := CancelOrderCmd.Flags()
	flags.StringVar(&optionOrderID, "id", "", "Order id (required if origclordid empty)")
	flags.StringVar(&optionClientOrderID, "clordid", "", "Client order id of the cancel request (uuid autogenerated if not given)")
	flags.StringVar(&optionOrigClientOrderID, "origclordid", "", "Client order id of the order to cancel (required if id empty, and by FIX 4.x)")

	flags.StringVar(&optionOrderSide, "side", "", "Order side (buy, sell ... etc)")
	flags.StringVar(&optionOrderSymbol, "symbol", "", "Order symbol")
	flags.DurationVar(&optionExecReportsTimeout, "exec-reports-timeout", 5*time.Second, "Fail if the order is not canceled within timeout (0s wait indefinitely)")

	partyIDOptions = options.NewPartyIDOptions(CancelOrderCmd)

	options.Must(CancelOrderCmd.MarkFlagRequired("side"))

	options.Must(CancelOrderCmd.RegisterFlagCompletionFunc("side", complete.OrderSide))
	options.Must(CancelOrderCmd.RegisterFlagCompletionFunc("symbol", cobra.NoFileCompletions))
}

// Validate checks the options, then that the cancel request fits the
// session, before connecting.
func Validate(cmd *cobra.Command, args []string) error {
	if err := validateOptions(); err != nil {
		return err
	}

	s, err := config.CurrentSession()
	if err != nil {
		return err
	}

	request, err := buildMessage(s)
	if err != nil {
		return err
	}

	return s.Check(request)
}

func validateOptions() error {
	if _, err := options.Side(optionOrderSide); err != nil {
		return err
	}

	if len(optionOrderID) == 0 && len(optionOrigClientOrderID) == 0 {
		return fmt.Errorf("%w: --id or --origclordid required", errors.ErrOptions)
	}

	if len(optionClientOrderID) == 0 {
		optionClientOrderID = uuid.NewString()
	}

	return partyIDOptions.Validate()
}

func Execute(cmd *cobra.Command, args []string) error {
	ctx := cmd.Context()

	c, err := initiator.Connect(ctx, initiator.Options{
		MsgTypes: []string{
			string(fix50sp2.MsgTypeExecutionreport),
			string(fix50sp2.MsgTypeOrdercancelreject),
		},
	})
	if err != nil {
		return err
	}
	defer c.Close(true)

	request, err := buildMessage(c.Session)
	if err != nil {
		return err
	}

	if _, err := c.Send(ctx, request); err != nil {
		return err
	}

	h := &handler{out: cmd.OutOrStdout(), dictionary: c.Dictionary, logger: config.GetLogger()}

	return c.Await(ctx, initiator.AwaitOptions{What: "order cancellation", Timeout: optionExecReportsTimeout}, h.handle)
}

func buildMessage(s *config.Session) (*fix50sp2.OrderCancelRequestBuilder, error) {
	if err := s.CheckSupported(); err != nil {
		return nil, err
	}

	// FIX 4.3 and 4.4 require OrigClOrdID.
	if len(optionOrigClientOrderID) == 0 && s.Requires(string(fix50sp2.MsgTypeOrdercancelrequest), fix50sp2.TagOrigClOrdID) {
		return nil, fmt.Errorf("%w: %s requires --origclordid", errors.ErrOptions, s.Version())
	}

	side, err := options.Side(optionOrderSide)
	if err != nil {
		return nil, err
	}

	message := fix50sp2.BuildOrderCancelRequest(s.BeginString).
		SetClOrdID(optionClientOrderID).
		SetSide(side).
		SetTransactTime(time.Now())
	if len(optionOrderID) > 0 {
		message.SetOrderID(optionOrderID)
	}
	if len(optionOrigClientOrderID) > 0 {
		message.SetOrigClOrdID(optionOrigClientOrderID)
	}
	if len(optionOrderSymbol) > 0 {
		message.SetSymbol(optionOrderSymbol)
	}
	for _, entry := range partyIDOptions.PartyEntries(s) {
		message.AddNoPartyIDsEntry(entry)
	}

	return message, nil
}

// handler follows the responses to the cancel request, those whose ClOrdID
// or OrigClOrdID is the request's or the order's.
type handler struct {
	out        io.Writer
	dictionary *dictionary.Dict
	logger     *zerolog.Logger
}

// handle handles a response: it is done once the order is canceled, fails
// on an OrderCancelReject or a rejection, and waits through the other
// statuses, pending ones included.
func (h *handler) handle(m *fix.Message) (bool, error) {
	if !h.matches(m) {
		h.logger.Debug().Msgf("Ignoring message of another order: %s", m.Get(fix50sp2.TagClOrdID))
		return false, initiator.ErrSkip
	}

	utils.WriteMessageBodyAsTable(h.out, m, h.dictionary)

	if string(m.MsgType()) == string(fix50sp2.MsgTypeOrdercancelreject) {
		return true, options.WithText(errors.ErrFixOrderRejected, m)
	}

	ordStatus, ok := fix50sp2.WrapExecutionReport(m).OrdStatus()
	if !ok {
		return true, fmt.Errorf("%w: missing OrdStatus", errors.ErrFix)
	}

	switch ordStatus {
	case fix50sp2.OrdStatusCanceled:
		return true, nil
	case fix50sp2.OrdStatusRejected:
		return true, options.WithText(errors.ErrFixOrderRejected, m)
	default:
		return false, nil
	}
}

// matches reports whether m is about the cancel request or the order: by
// ClOrdID or OrigClOrdID, or OrderID if --id was given.
func (h *handler) matches(m *fix.Message) bool {
	ids := []string{optionClientOrderID}
	if len(optionOrigClientOrderID) > 0 {
		ids = append(ids, optionOrigClientOrderID)
	}

	if slices.Contains(ids, string(m.Get(fix50sp2.TagClOrdID))) || slices.Contains(ids, string(m.Get(fix50sp2.TagOrigClOrdID))) {
		return true
	}

	return len(optionOrderID) > 0 && string(m.Get(fix50sp2.TagOrderID)) == optionOrderID
}
