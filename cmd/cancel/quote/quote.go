package cancelquote

import (
	"fmt"
	"io"
	"slices"
	"time"

	"github.com/google/uuid"
	"github.com/rs/zerolog"
	"github.com/spf13/cobra"
	"github.com/sylr/fix2/fix"
	"github.com/sylr/fix2/fix/dictionary"

	"sylr.dev/fix/v2/cli/options"
	"sylr.dev/fix/v2/config"
	"sylr.dev/fix/v2/errors"
	"sylr.dev/fix/v2/fix50sp2"
	"sylr.dev/fix/v2/initiator"
	"sylr.dev/fix/v2/utils"
)

var (
	optionQuoteSymbols       []string
	optionQuoteID            string
	optionExecReportsTimeout time.Duration
	partyIDOptions           *options.PartyIDOptions

	// quoteMsgID is the QuoteMsgID of the request, sent if the session's
	// FIX version defines it.
	quoteMsgID string
)

var CancelQuoteCmd = &cobra.Command{
	Use:               "quote",
	Short:             "Cancel quote",
	Long:              "Send a quote cancel request after initiating a session with a FIX acceptor, and wait for the quotes to be canceled.",
	Args:              cobra.ExactArgs(0),
	ValidArgsFunction: cobra.NoFileCompletions,
	PersistentPreRunE: Validate,
	RunE:              Execute,
}

func init() {
	flags := CancelQuoteCmd.Flags()
	flags.StringVar(&optionQuoteID, "id", "", "Quote id (uuid autogenerated if not given)")
	flags.StringSliceVar(&optionQuoteSymbols, "symbols", []string{}, "Symbols of the quotes to cancel")
	flags.DurationVar(&optionExecReportsTimeout, "exec-reports-timeout", 5*time.Second, "Fail if the quotes are not canceled within timeout (0s wait indefinitely)")

	partyIDOptions = options.NewPartyIDOptions(CancelQuoteCmd)

	options.Must(CancelQuoteCmd.RegisterFlagCompletionFunc("symbols", cobra.NoFileCompletions))
}

// Validate checks the options, then that the request fits the session,
// before connecting.
func Validate(cmd *cobra.Command, args []string) error {
	if err := validateOptions(); err != nil {
		return err
	}

	s, err := config.CurrentSession()
	if err != nil {
		return err
	}

	request, err := buildMessage(s)
	if err != nil {
		return err
	}

	return s.Check(request)
}

func validateOptions() error {
	if len(optionQuoteSymbols) == 0 || slices.Contains(optionQuoteSymbols, "") {
		return errors.ErrOptionsNoSymbolGiven
	}

	if len(optionQuoteID) == 0 {
		optionQuoteID = uuid.NewString()
	}
	quoteMsgID = uuid.NewString()

	return partyIDOptions.Validate()
}

func Execute(cmd *cobra.Command, args []string) error {
	ctx := cmd.Context()

	c, err := initiator.Connect(ctx, initiator.Options{
		MsgTypes: []string{
			string(fix50sp2.MsgTypeQuotestatusreport),
			string(fix50sp2.MsgTypeMassquoteack),
		},
	})
	if err != nil {
		return err
	}
	defer c.Close(true)

	request, err := buildMessage(c.Session)
	if err != nil {
		return err
	}

	if _, err := c.Send(ctx, request); err != nil {
		return err
	}

	h := &handler{out: cmd.OutOrStdout(), dictionary: c.Dictionary, logger: config.GetLogger()}

	return c.Await(ctx, initiator.AwaitOptions{What: "quote status report", Timeout: optionExecReportsTimeout}, h.handle)
}

func buildMessage(s *config.Session) (*fix50sp2.QuoteCancelBuilder, error) {
	if err := s.CheckSupported(); err != nil {
		return nil, err
	}

	message := fix50sp2.BuildQuoteCancel(s.BeginString).
		SetQuoteID(optionQuoteID)
	// FIX 4.3 and 4.4 do not define QuoteMsgID in a QuoteCancel.
	if s.Defines(string(fix50sp2.MsgTypeQuotecancel), fix50sp2.TagQuoteMsgID) {
		message.SetQuoteMsgID(quoteMsgID)
	}
	message.SetQuoteCancelType(fix50sp2.QuoteCancelTypeCancelForOneOrMoreSecurities)
	for _, entry := range partyIDOptions.PartyEntries(s) {
		message.AddNoPartyIDsEntry(entry)
	}
	for _, symbol := range optionQuoteSymbols {
		message.AddNoQuoteEntriesEntry(fix50sp2.NewNoQuoteEntriesEntry().SetSymbol(symbol))
	}

	return message, nil
}

// handler waits for the QuoteStatusReport, or the MassQuoteAcknowledgement,
// answering the request: the one whose QuoteMsgID, or else QuoteID, is the
// request's.
type handler struct {
	out        io.Writer
	dictionary *dictionary.Dict
	logger     *zerolog.Logger
}

// handle handles a response: it is done once the quotes are canceled,
// fails if the request was rejected or the quote not found, and waits
// through the other statuses.
func (h *handler) handle(m *fix.Message) (bool, error) {
	if !matches(m) {
		h.logger.Debug().Msgf("Ignoring %s message of another quote: %s", m.MsgType(), m.Get(fix50sp2.TagQuoteID))
		return false, initiator.ErrSkip
	}

	utils.WriteMessageBodyAsTable(h.out, m, h.dictionary)

	if m.Get(fix50sp2.TagQuoteRejectReason) != nil {
		return true, options.WithText(errors.ErrFixQuoteRejected, m)
	}

	switch fix50sp2.QuoteStatus(m.Get(fix50sp2.TagQuoteStatus)) {
	case fix50sp2.QuoteStatusCanceled,
		fix50sp2.QuoteStatusCanceledAll,
		fix50sp2.QuoteStatusCanceledForSpecificSecurities,
		fix50sp2.QuoteStatusCanceledForSpecificSecuritytypes,
		fix50sp2.QuoteStatusCanceledForUnderlying,
		fix50sp2.QuoteStatusRemovedFromMarket:
		return true, nil
	case fix50sp2.QuoteStatusRejected:
		return true, options.WithText(errors.ErrFixQuoteRejected, m)
	case fix50sp2.QuoteStatusQuoteNotFound:
		return true, options.WithText(fmt.Errorf("%w: quote not found", errors.ErrFixQuoteRejected), m)
	case "":
		return true, fmt.Errorf("%w: missing QuoteStatus", errors.ErrFix)
	default:
		return false, nil
	}
}

// matches reports whether m answers the request.
func matches(m *fix.Message) bool {
	if id := m.Get(fix50sp2.TagQuoteMsgID); id != nil {
		return string(id) == quoteMsgID
	}

	return string(m.Get(fix50sp2.TagQuoteID)) == optionQuoteID
}
