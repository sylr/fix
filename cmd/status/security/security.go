package statussecurity

import (
	"fmt"
	"strings"

	"github.com/google/uuid"
	"github.com/spf13/cobra"
	"github.com/sylr/fix2/fix"
	"github.com/sylr/fix2/fix/session"

	"sylr.dev/fix/v2/cli/complete"
	"sylr.dev/fix/v2/cli/options"
	"sylr.dev/fix/v2/config"
	"sylr.dev/fix/v2/dict"
	"sylr.dev/fix/v2/errors"
	"sylr.dev/fix/v2/fix50sp2"
	"sylr.dev/fix/v2/initiator"
	"sylr.dev/fix/v2/utils"
)

var (
	optionSecurityStatusReqID string
	optionSubType             string
	optionSymbol              string
)

var StatusSecurityCmd = &cobra.Command{
	Use:   "security",
	Short: "Request the status of a security",
	Long: "Send a SecurityStatusRequest after initiating a session with a FIX acceptor, and print the " +
		"SecurityStatus answering it; with --subscription-type snapshot_plus_updates, print the updates " +
		"until interrupted.",
	Args:              cobra.ExactArgs(0),
	ValidArgsFunction: cobra.NoFileCompletions,
	PersistentPreRunE: utils.MakePersistentPreRunE(Validate),
	RunE:              Execute,
}

func init() {
	StatusSecurityCmd.Flags().StringVar(&optionSymbol, "symbol", "", "Symbol")
	StatusSecurityCmd.Flags().StringVar(&optionSubType, "subscription-type", "snapshot", "Subscription type (snapshot, snapshot_plus_updates ... etc)")
	StatusSecurityCmd.Flags().StringVar(&optionSecurityStatusReqID, "security-status-request-id", "", "SecurityStatusReqID (uuid autogenerated if not given)")

	if err := StatusSecurityCmd.RegisterFlagCompletionFunc("subscription-type", complete.SubscriptionRequestTypes); err != nil {
		panic(err)
	}
	if err := StatusSecurityCmd.RegisterFlagCompletionFunc("symbol", cobra.NoFileCompletions); err != nil {
		panic(err)
	}
}

func Validate(cmd *cobra.Command, args []string) error {
	if len(optionSymbol) == 0 {
		return fmt.Errorf("%w: --symbol can not be empty", errors.ErrOptions)
	}

	if _, ok := dict.SubscriptionRequestTypes[strings.ToUpper(optionSubType)]; !ok {
		return fmt.Errorf("%w: unknown subscription type `%s`", errors.ErrOptions, optionSubType)
	}

	if len(optionSecurityStatusReqID) == 0 {
		optionSecurityStatusReqID = uuid.NewString()
	}

	return nil
}

func Execute(cmd *cobra.Command, args []string) error {
	ctx := cmd.Context()

	s, err := config.CurrentSession()
	if err != nil {
		return err
	}

	request, err := buildMessage(s)
	if err != nil {
		return err
	}

	c, err := initiator.Connect(ctx, initiator.Options{
		MsgTypes: []string{string(fix50sp2.MsgTypeSecuritystatus)},
	})
	if err != nil {
		return err
	}
	defer c.Close(true)

	if _, err := c.Send(ctx, request); err != nil {
		return err
	}

	subscribed := dict.SubscriptionRequestTypes[strings.ToUpper(optionSubType)] == fix50sp2.SubscriptionRequestTypeSnapshotPlusUpdates
	opts := initiator.AwaitOptions{What: "security status", Timeout: config.Timeout(0)}
	if subscribed {
		opts.Mode = initiator.TimeoutFirst
	}

	return c.Await(ctx, opts, func(m *fix.Message) (bool, error) {
		if id := string(m.Get(fix50sp2.TagSecurityStatusReqID)); id != optionSecurityStatusReqID {
			config.GetLogger().Info().Msgf("Ignoring the security status of another request: %q", id)
			return false, initiator.ErrSkip
		}

		utils.WriteMessageBodyAsTable(cmd.OutOrStdout(), m, c.Dictionary)

		if status, _ := fix50sp2.WrapSecurityStatus(m).SecurityTradingStatus(); status == fix50sp2.SecurityTradingStatusUnknownOrInvalid {
			return true, options.WithText(fmt.Errorf("%w: unknown or invalid security %q", errors.ErrFixRejected, m.Get(fix50sp2.TagSymbol)), m)
		}

		return !subscribed, nil
	})
}

// buildMessage builds the SecurityStatusRequest for session s.
func buildMessage(s *config.Session) (session.Outgoing, error) {
	if err := s.CheckSupported(); err != nil {
		return nil, err
	}

	return fix50sp2.BuildSecurityStatusRequest(s.BeginString).
		SetSecurityStatusReqID(optionSecurityStatusReqID).
		SetSymbol(optionSymbol).
		SetSubscriptionRequestType(dict.SubscriptionRequestTypes[strings.ToUpper(optionSubType)]), nil
}
