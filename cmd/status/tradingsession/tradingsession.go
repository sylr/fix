package statustradingsession

import (
	"fmt"
	"strings"

	"github.com/google/uuid"
	"github.com/spf13/cobra"
	"github.com/sylr/fix2/fix"
	"github.com/sylr/fix2/fix/session"

	"sylr.dev/fix/v2/cli/complete"
	"sylr.dev/fix/v2/cli/options"
	"sylr.dev/fix/v2/config"
	"sylr.dev/fix/v2/dict"
	"sylr.dev/fix/v2/errors"
	"sylr.dev/fix/v2/fix50sp2"
	"sylr.dev/fix/v2/initiator"
	"sylr.dev/fix/v2/utils"
)

var (
	optionTradSesReqID     string
	optionTradingSessionID string
	optionSubType          string
)

var StatusTradingSessionCmd = &cobra.Command{
	Use:   "tradingsession",
	Short: "Request the status of a trading session",
	Long: "Send a TradingSessionStatusRequest after initiating a session with a FIX acceptor, and print the " +
		"TradingSessionStatus answering it; with --subscription-type snapshot_plus_updates, print the updates " +
		"until interrupted.",
	Args:              cobra.ExactArgs(0),
	ValidArgsFunction: cobra.NoFileCompletions,
	PersistentPreRunE: utils.MakePersistentPreRunE(Validate),
	RunE:              Execute,
}

func init() {
	StatusTradingSessionCmd.Flags().StringVar(&optionTradSesReqID, "request-id", "", "TradSesReqID (uuid autogenerated if not given)")
	StatusTradingSessionCmd.Flags().StringVar(&optionTradingSessionID, "trading-session-id", "", "TradingSessionID, every trading session if not given")
	StatusTradingSessionCmd.Flags().StringVar(&optionSubType, "subscription-type", "snapshot", "Subscription type (snapshot, snapshot_plus_updates ... etc)")

	if err := StatusTradingSessionCmd.RegisterFlagCompletionFunc("subscription-type", complete.SubscriptionRequestTypes); err != nil {
		panic(err)
	}
	if err := StatusTradingSessionCmd.RegisterFlagCompletionFunc("trading-session-id", cobra.NoFileCompletions); err != nil {
		panic(err)
	}
}

func Validate(cmd *cobra.Command, args []string) error {
	if _, ok := dict.SubscriptionRequestTypes[strings.ToUpper(optionSubType)]; !ok {
		return fmt.Errorf("%w: unknown subscription type `%s`", errors.ErrOptions, optionSubType)
	}

	if len(optionTradSesReqID) == 0 {
		optionTradSesReqID = uuid.NewString()
	}

	return nil
}

func Execute(cmd *cobra.Command, args []string) error {
	ctx := cmd.Context()

	s, err := config.CurrentSession()
	if err != nil {
		return err
	}

	request, err := buildMessage(s)
	if err != nil {
		return err
	}

	c, err := initiator.Connect(ctx, initiator.Options{
		MsgTypes: []string{string(fix50sp2.MsgTypeTradingsessionstatus)},
	})
	if err != nil {
		return err
	}
	defer c.Close(true)

	if _, err := c.Send(ctx, request); err != nil {
		return err
	}

	subscribed := dict.SubscriptionRequestTypes[strings.ToUpper(optionSubType)] == fix50sp2.SubscriptionRequestTypeSnapshotPlusUpdates
	opts := initiator.AwaitOptions{What: "trading session status", Timeout: config.Timeout(0)}
	if subscribed {
		opts.Mode = initiator.TimeoutFirst
	}

	return c.Await(ctx, opts, func(m *fix.Message) (bool, error) {
		if id := string(m.Get(fix50sp2.TagTradSesReqID)); id != optionTradSesReqID {
			config.GetLogger().Info().Msgf("Ignoring the trading session status of another request: %q", id)
			return false, initiator.ErrSkip
		}

		utils.WriteMessageBodyAsTable(cmd.OutOrStdout(), m, c.Dictionary)

		status := fix50sp2.WrapTradingSessionStatus(m)
		if st, _ := status.TradSesStatus(); st == fix50sp2.TradSesStatusRequestRejected {
			err := fmt.Errorf("%w: trading session status request", errors.ErrFixRejected)
			if reason, ok := status.TradSesStatusRejReason(); ok {
				err = fmt.Errorf("%w, reason %s", err, reason)
			}
			return true, options.WithText(err, m)
		}

		return !subscribed, nil
	})
}

// buildMessage builds the TradingSessionStatusRequest for session s.
func buildMessage(s *config.Session) (session.Outgoing, error) {
	if err := s.CheckSupported(); err != nil {
		return nil, err
	}

	message := fix50sp2.BuildTradingSessionStatusRequest(s.BeginString).
		SetTradSesReqID(optionTradSesReqID).
		SetSubscriptionRequestType(dict.SubscriptionRequestTypes[strings.ToUpper(optionSubType)])

	if len(optionTradingSessionID) > 0 {
		message.SetTradingSessionID(fix50sp2.TradingSessionID(optionTradingSessionID))
	}

	return message, nil
}
