var (
	optionTypes       []string
	optionSymbols     []string
	optionSubType     string
	optionUpdateType  string
	optionMDReqID     string
	optionPrintData   bool
	optionMarketDepth int
	optionNoLogout    bool
)

var MarketDataRequestCmd = &cobra.Command{
	Use:   "request",
	Short: "Send a MarketDataRequest FIX message",
	Long: "Send a MarketDataRequest after initiating a session with a FIX acceptor, and print the market data " +
		"answering it: a snapshot of each symbol, or with --sub-type snapshot_plus_updates, the snapshots " +
		"and the updates until interrupted.",
	Args:              cobra.ExactArgs(0),
	ValidArgsFunction: cobra.NoFileCompletions,
	PersistentPreRunE: utils.MakePersistentPreRunE(Validate),
	RunE:              Execute,
}

func init() {
	MarketDataRequestCmd.Flags().StringArrayVar(&optionSymbols, "symbol", []string{}, "Symbols")
	MarketDataRequestCmd.Flags().StringArrayVar(&optionTypes, "type", []string{"bid", "offer"}, "MD entry types (bid, offer, trade ... etc)")
	MarketDataRequestCmd.Flags().StringVar(&optionSubType, "sub-type", "snapshot", "Subscription type (snapshot, snapshot_plus_updates ... etc)")
	MarketDataRequestCmd.Flags().StringVar(&optionUpdateType, "update-type", "incremental_refresh", "Update type (full_refresh, incremental_refresh)")
	MarketDataRequestCmd.Flags().StringVar(&optionMDReqID, "id", "", "MDReqID (uuid autogenerated if not given)")
	MarketDataRequestCmd.Flags().BoolVar(&optionPrintData, "print-data", true, "Print data")
	MarketDataRequestCmd.Flags().IntVar(&optionMarketDepth, "depth", 0, "Market depth (0: full book)")
	MarketDataRequestCmd.Flags().BoolVar(&optionNoLogout, "no-logout", false, "Do not send FIX logout")

	for flag, f := range map[string]cobra.CompletionFunc{
		"symbol":      cobra.NoFileCompletions,
		"type":        complete.MDEntryTypes,
		"sub-type":    complete.SubscriptionRequestTypes,
		"update-type": complete.MDUpdateTypes,
	} {
		if err := MarketDataRequestCmd.RegisterFlagCompletionFunc(flag, f); err != nil {
			panic(err)
		}
	}
}

func Validate(cmd *cobra.Command, args []string) error {
	if len(optionSymbols) == 0 {
		return errors.ErrOptionsNoSymbolGiven
	}
	if slices.Contains(optionSymbols, "") {
		return fmt.Errorf("%w: --symbol can not be empty", errors.ErrOptions)
	}

	if len(optionTypes) == 0 {
		return errors.ErrOptionsNoTypeGiven
	}
	for _, t := range optionTypes {
		if _, ok := dict.MDEntryTypes[strings.ToUpper(t)]; !ok {
			return fmt.Errorf("%w: unknown type `%s`", errors.ErrOptions, t)
		}
	}

	if _, ok := dict.SubscriptionRequestTypes[strings.ToUpper(optionSubType)]; !ok {
		return fmt.Errorf("%w: unknown subscription type `%s`", errors.ErrOptions, optionSubType)
	}

	if _, ok := dict.MDUpdateTypes[strings.ToUpper(optionUpdateType)]; !ok {
		return fmt.Errorf("%w: unknown update type `%s`", errors.ErrOptions, optionUpdateType)
	}

	if optionMarketDepth < 0 {
		return fmt.Errorf("%w: --depth can not be negative", errors.ErrOptions)
	}

	if len(optionMDReqID) == 0 {
		optionMDReqID = uuid.NewString()
	}

	return nil
}

func Execute(cmd *cobra.Command, args []string) error {
	ctx := cmd.Context()

	s, err := config.CurrentSession()
	if err != nil {
		return err
	}

	request, err := buildMessage(s)
	if err != nil {
		return err
	}

	c, err := initiator.Connect(ctx, initiator.Options{
		MsgTypes: []string{
			string(fix50sp2.MsgTypeMarketdatasnapshotfullrefresh),
			string(fix50sp2.MsgTypeMarketdataincrementalrefresh),
			string(fix50sp2.MsgTypeMarketdatarequestreject),
		},
	})
	if err != nil {
		return err
	}
	defer c.Close(!optionNoLogout)

	handler := &marketdata.RequestHandler{Dictionary: c.Dictionary}
	if optionPrintData {
		handler.Writer = cmd.OutOrStdout()
	}

	if _, err := c.Send(ctx, request); err != nil {
		return err
	}

	// A snapshot is done once every symbol's came, within the timeout; a
	// subscription, once interrupted.
	subscribed := dict.SubscriptionRequestTypes[strings.ToUpper(optionSubType)] == fix50sp2.SubscriptionRequestTypeSnapshotPlusUpdates
	opts := initiator.AwaitOptions{What: "market data", Timeout: config.Timeout(0)}
	if subscribed {
		opts.Mode = initiator.TimeoutFirst
	}

	pending := map[string]bool{}
	for _, symbol := range optionSymbols {
		pending[symbol] = true
	}

	return c.Await(ctx, opts, func(m *fix.Message) (bool, error) {
		if id := string(m.Get(fix50sp2.TagMDReqID)); id != optionMDReqID {
			config.GetLogger().Info().Msgf("Ignoring the market data of another request: %q", id)
			return false, initiator.ErrSkip
		}

		if err := handler.Handle(m); err != nil {
			return true, err
		}

		if string(m.MsgType()) == string(fix50sp2.MsgTypeMarketdatasnapshotfullrefresh) {
			if symbol := string(m.Get(fix50sp2.TagSymbol)); symbol != "" {
				delete(pending, symbol)
			} else {
				// A snapshot not telling its symbol: one of those
				// requested is done.
				for symbol := range pending {
					delete(pending, symbol)
					break
				}
			}
		}

		return !subscribed && len(pending) == 0, nil
	})
}

// buildMessage builds the MarketDataRequest for session s.
func buildMessage(s *config.Session) (session.Outgoing, error) {
	if err := s.CheckSupported(); err != nil {
		return nil, err
	}

	message := fix50sp2.BuildMarketDataRequest(s.BeginString).
		SetMDReqID(optionMDReqID).
		SetSubscriptionRequestType(dict.SubscriptionRequestTypes[strings.ToUpper(optionSubType)]).
		SetMarketDepth(optionMarketDepth).
		SetMDUpdateType(dict.MDUpdateTypes[strings.ToUpper(optionUpdateType)])

	for _, t := range optionTypes {
		message.AddNoMDEntryTypesEntry(fix50sp2.NewNoMDEntryTypesEntry().SetMDEntryType(dict.MDEntryTypes[strings.ToUpper(t)]))
	}

	for _, symbol := range optionSymbols {
		message.AddNoRelatedSymEntry(fix50sp2.NewNoRelatedSymEntry().SetSymbol(symbol))
	}

	return message, nil
}
