//go:build validator

package marketdatavalidator

import (
	"fmt"

	"github.com/google/uuid"
	"github.com/spf13/cobra"
	"github.com/sylr/fix2/fix"
	"github.com/sylr/fix2/fix/session"

	"sylr.dev/fix/v2/config"
	"sylr.dev/fix/v2/errors"
	"sylr.dev/fix/v2/fix50sp2"
	"sylr.dev/fix/v2/initiator"
	"sylr.dev/fix/v2/marketdata"
	"sylr.dev/fix/v2/utils"
)

var (
	optionSymbol       string
	optionMDReqID      string
	optionTradeHistory bool
)

var MarketDataValidatorCmd = &cobra.Command{
	Use:   "validator",
	Short: "Validate the market data of a symbol",
	Long: "Subscribe to the market data of a symbol after initiating a session with a FIX acceptor, and " +
		"report the inconsistencies of its book as metrics until interrupted.",
	Args:              cobra.ExactArgs(0),
	ValidArgsFunction: cobra.NoFileCompletions,
	PersistentPreRunE: utils.MakePersistentPreRunE(Validate),
	RunE:              Execute,
}

func init() {
	MarketDataValidatorCmd.Flags().StringVar(&optionSymbol, "symbol", "", "Symbol")
	MarketDataValidatorCmd.Flags().StringVar(&optionMDReqID, "id", "", "MDReqID (uuid autogenerated if not given)")
	MarketDataValidatorCmd.Flags().BoolVar(&optionTradeHistory, "trade-history", true, "Subscribe to the trade history too, MDEntryType 101, which FIX does not define")

	if err := MarketDataValidatorCmd.RegisterFlagCompletionFunc("symbol", cobra.NoFileCompletions); err != nil {
		panic(err)
	}
}

func Validate(cmd *cobra.Command, args []string) error {
	if len(optionSymbol) == 0 {
		return fmt.Errorf("%w: --symbol can not be empty", errors.ErrOptions)
	}

	if len(optionMDReqID) == 0 {
		optionMDReqID = uuid.NewString()
	}

	return nil
}

func Execute(cmd *cobra.Command, args []string) error {
	ctx := cmd.Context()
	logger := config.GetLogger()

	s, err := config.CurrentSession()
	if err != nil {
		return err
	}

	request, err := buildMessage(s)
	if err != nil {
		return err
	}

	c, err := initiator.Connect(ctx, initiator.Options{
		MsgTypes: []string{
			string(fix50sp2.MsgTypeMarketdatasnapshotfullrefresh),
			string(fix50sp2.MsgTypeMarketdataincrementalrefresh),
			string(fix50sp2.MsgTypeMarketdatarequestreject),
		},
	})
	if err != nil {
		return err
	}
	defer c.Close(true)

	validator := marketdata.NewValidator(logger, optionSymbol)

	if _, err := c.Send(ctx, request); err != nil {
		return err
	}

	opts := initiator.AwaitOptions{What: "market data", Timeout: config.Timeout(0), Mode: initiator.TimeoutFirst}

	return c.Await(ctx, opts, func(m *fix.Message) (bool, error) {
		if id := string(m.Get(fix50sp2.TagMDReqID)); id != optionMDReqID {
			logger.Info().Msgf("Ignoring the market data of another request: %q", id)
			return false, initiator.ErrSkip
		}

		if string(m.MsgType()) == string(fix50sp2.MsgTypeMarketdatarequestreject) {
			// It returns the reject as an error.
			return true, (&marketdata.RequestHandler{Dictionary: c.Dictionary}).Handle(m)
		}

		return false, validator.Handle(m)
	})
}

// buildMessage builds the MarketDataRequest for session s: a subscription
// to the bids, offers, trades and, with --trade-history, trade history of
// the symbol.
func buildMessage(s *config.Session) (session.Outgoing, error) {
	if err := s.CheckSupported(); err != nil {
		return nil, err
	}

	message := fix50sp2.BuildMarketDataRequest(s.BeginString).
		SetMDReqID(optionMDReqID).
		SetSubscriptionRequestType(fix50sp2.SubscriptionRequestTypeSnapshotPlusUpdates).
		SetMarketDepth(0).
		SetMDUpdateType(fix50sp2.MDUpdateTypeIncrementalRefresh).
		AddNoMDEntryTypesEntry(fix50sp2.NewNoMDEntryTypesEntry().SetMDEntryType(fix50sp2.MDEntryTypeBid)).
		AddNoMDEntryTypesEntry(fix50sp2.NewNoMDEntryTypesEntry().SetMDEntryType(fix50sp2.MDEntryTypeOffer)).
		AddNoMDEntryTypesEntry(fix50sp2.NewNoMDEntryTypesEntry().SetMDEntryType(fix50sp2.MDEntryTypeTrade)).
		AddNoRelatedSymEntry(fix50sp2.NewNoRelatedSymEntry().SetSymbol(optionSymbol))

	if optionTradeHistory {
		message.AddNoMDEntryTypesEntry(fix50sp2.NewNoMDEntryTypesEntry().SetMDEntryType(fix50sp2.MDEntryType("101")))
	}

	return message, nil
}
