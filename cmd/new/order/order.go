var (
	optionOrderSide, optionOrderType string
	optionOrderSymbol, optionOrderID string
	optionOrderExpiry                string
	optionOrderQuantity              options.Decimal
	optionOrderPrice                 options.Decimal
	optionOrderOrigination           string
	partyIDOptions                   *options.PartyIDOptions
	attributeOptions                 *options.AttributeOptions
	optionExecReports                int
	optionExecReportsTimeout         time.Duration
	optionExecReportsTimeoutReset    bool
	optionStopOnFinalState           bool
	optionUpdatePeriod               time.Duration
	optionUpdateOrderQuantity        options.Decimal
	optionUpdateOrderPrice           options.Decimal
)

var NewOrderCmd = &cobra.Command{
	Use:               "order",
	Short:             "New single order",
	Long:              "Send a new single order after initiating a session with a FIX acceptor.",
	Args:              cobra.ExactArgs(0),
	ValidArgsFunction: cobra.NoFileCompletions,
	PersistentPreRunE: Validate,
	RunE:              Execute,
}

func init() {
	flags := NewOrderCmd.Flags()
	flags.StringVar(&optionOrderID, "id", "", "Client order id (uuid autogenerated if not given)")
	flags.StringVar(&optionOrderSide, "side", "", "Order side (buy, sell ... etc)")
	flags.StringVar(&optionOrderType, "type", "", "Order type (market, limit, stop ... etc)")
	flags.StringVar(&optionOrderSymbol, "symbol", "", "Order symbol")
	flags.Var(&optionOrderQuantity, "quantity", "Order quantity")
	flags.StringVar(&optionOrderExpiry, "expiry", "day", "Order expiry (day, good_till_cancel ... etc)")
	flags.Var(&optionOrderPrice, "price", "Order price (not for market orders)")
	flags.StringVar(&optionOrderOrigination, "origination", "", "Order origination")

	partyIDOptions = options.NewPartyIDOptions(NewOrderCmd)
	attributeOptions = options.NewAttributeOptions(NewOrderCmd)

	flags.IntVar(&optionExecReports, "exec-reports", 1, "Expect given number of execution reports, pending ones aside, before logging out (0 wait until interrupted)")
	flags.DurationVar(&optionExecReportsTimeout, "exec-reports-timeout", 5*time.Second, "Fail if the execution reports are not received within timeout, or the first one with --exec-reports 0 (0s wait indefinitely)")
	flags.BoolVar(&optionExecReportsTimeoutReset, "exec-reports-timeout-reset", false, "Reset execution reports timeout each time an execution report is received")

	flags.BoolVar(&optionStopOnFinalState, "stop-on-final-state", false, "Stop when the order reaches a final state")

	flags.DurationVar(&optionUpdatePeriod, "update-period", 0, "Period for recurring order price/quantity updates")
	flags.Var(&optionUpdateOrderQuantity, "update-order-quantity", "Add to the order quantity at each update")
	flags.Var(&optionUpdateOrderPrice, "update-order-price", "Add to the order price at each update")

	options.Must(NewOrderCmd.MarkFlagRequired("side"))
	options.Must(NewOrderCmd.MarkFlagRequired("type"))
	options.Must(NewOrderCmd.MarkFlagRequired("symbol"))
	options.Must(NewOrderCmd.MarkFlagRequired("quantity"))

	options.Must(NewOrderCmd.RegisterFlagCompletionFunc("side", complete.OrderSide))
	options.Must(NewOrderCmd.RegisterFlagCompletionFunc("type", complete.OrderType))
	options.Must(NewOrderCmd.RegisterFlagCompletionFunc("expiry", complete.OrderTimeInForce))
	options.Must(NewOrderCmd.RegisterFlagCompletionFunc("symbol", cobra.NoFileCompletions))
	options.Must(NewOrderCmd.RegisterFlagCompletionFunc("origination", complete.OrderOriginationRole))
}

// Validate checks the options, then that the order fits the session, before
// connecting.
func Validate(cmd *cobra.Command, args []string) error {
	if err := validateOptions(); err != nil {
		return err
	}

	s, err := config.CurrentSession()
	if err != nil {
		return err
	}

	order, err := buildMessage(s)
	if err != nil {
		return err
	}

	return s.Check(order)
}

func validateOptions() error {
	if _, err := options.Side(optionOrderSide); err != nil {
		return err
	}

	ordType, err := options.OrdType(optionOrderType)
	if err != nil {
		return err
	}

	if _, err := options.TimeInForce(optionOrderExpiry); err != nil {
		return err
	}

	if len(optionOrderSymbol) == 0 {
		return errors.ErrOptionsNoSymbolGiven
	}

	if err := options.Positive("quantity", optionOrderQuantity.Value()); err != nil {
		return err
	}

	if err := options.CheckPrice(ordType, optionOrderPrice); err != nil {
		return err
	}

	if optionUpdatePeriod > 0 && ordType == fix50sp2.OrdTypeMarket && optionUpdateOrderPrice.IsSet() {
		return fmt.Errorf("%w: can't update the price of a market order", errors.ErrOptions)
	}

	if len(optionOrderOrigination) > 0 {
		if _, ok := options.Lookup(dict.OrderOriginations, optionOrderOrigination); !ok {
			return fmt.Errorf("%w: `%s`", errors.ErrOptionOrderOriginationUnknown, optionOrderOrigination)
		}
	}

	if len(optionOrderID) == 0 {
		optionOrderID = uuid.NewString()
	}

	if err := attributeOptions.Validate(); err != nil {
		return err
	}

	return partyIDOptions.Validate()
}

func Execute(cmd *cobra.Command, args []string) error {
	ctx := cmd.Context()

	c, err := initiator.Connect(ctx, initiator.Options{
		MsgTypes: []string{
			string(fix50sp2.MsgTypeExecutionreport),
			string(fix50sp2.MsgTypeOrdercancelreject),
		},
	})
	if err != nil {
		return err
	}
	defer c.Close(true)

	order, err := buildMessage(c.Session)
	if err != nil {
		return err
	}

	if _, err := c.Send(ctx, order); err != nil {
		return err
	}

	h := newHandler(cmd.OutOrStdout(), c.Dictionary, c.Session, func(m session.Outgoing) error {
		_, err := c.Send(ctx, m)
		return err
	})

	opts := initiator.AwaitOptions{What: "execution reports", Timeout: optionExecReportsTimeout}
	switch {
	case optionExecReportsTimeoutReset:
		opts.Mode = initiator.TimeoutIdle
	case optionExecReports == 0:
		opts.Mode = initiator.TimeoutFirst
	}

	if optionUpdatePeriod > 0 {
		ticker := time.NewTicker(optionUpdatePeriod)
		defer ticker.Stop()
		opts.Tick, opts.OnTick = ticker.C, h.update
	}

	return c.Await(ctx, opts, h.handle)
}

func buildMessage(s *config.Session) (*fix50sp2.NewOrderSingleBuilder, error) {
	if err := s.CheckSupported(); err != nil {
		return nil, err
	}

	side, err := options.Side(optionOrderSide)
	if err != nil {
		return nil, err
	}

	ordType, err := options.OrdType(optionOrderType)
	if err != nil {
		return nil, err
	}

	expiry, err := options.TimeInForce(optionOrderExpiry)
	if err != nil {
		return nil, err
	}

	message := fix50sp2.BuildNewOrderSingle(s.BeginString).
		SetClOrdID(optionOrderID).
		SetSide(side).
		SetTransactTime(time.Now()).
		SetOrdType(ordType).
		SetSymbol(optionOrderSymbol).
		SetTimeInForce(expiry)

	// FIX 4.3 requires HandlInst.
	if s.Requires(string(fix50sp2.MsgTypeNewordersingle), fix50sp2.TagHandlInst) {
		message.SetHandlInst(fix50sp2.HandlInstAutomatedExecutionOrderPrivateNoBrokerIntervention)
	}

	for _, entry := range partyIDOptions.PartyEntries(s) {
		message.AddNoPartyIDsEntry(entry)
	}

	for _, entry := range attributeOptions.AttributeEntries() {
		message.AddNoOrderAttributesEntry(entry)
	}

	message.SetString(fix50sp2.TagOrderQty, optionOrderQuantity.Value().String())

	if ordType != fix50sp2.OrdTypeMarket {
		message.SetString(fix50sp2.TagPrice, optionOrderPrice.Value().String())
	}

	if len(optionOrderOrigination) > 0 {
		origination, _ := options.Lookup(dict.OrderOriginations, optionOrderOrigination)
		message.SetOrderOrigination(origination)
	}

	return message, nil
}

// replacement is the ClOrdID, quantity and price of the order, once
// replaced.
type replacement struct {
	clOrdID         string
	quantity, price decimal.Decimal
}

// buildReplaceMessage builds the OrderCancelReplaceRequest of the order,
// whose ClOrdID is origClOrdID and OrderID orderID if known, to r.
func buildReplaceMessage(s *config.Session, origClOrdID, orderID string, r replacement) (*fix50sp2.OrderCancelReplaceRequestBuilder, error) {
	if err := s.CheckSupported(); err != nil {
		return nil, err
	}

	side, err := options.Side(optionOrderSide)
	if err != nil {
		return nil, err
	}

	ordType, err := options.OrdType(optionOrderType)
	if err != nil {
		return nil, err
	}

	expiry, err := options.TimeInForce(optionOrderExpiry)
	if err != nil {
		return nil, err
	}

	message := fix50sp2.BuildOrderCancelReplaceRequest(s.BeginString).
		SetClOrdID(r.clOrdID).
		SetOrigClOrdID(origClOrdID).
		SetSide(side).
		SetTransactTime(time.Now()).
		SetOrdType(ordType).
		SetTimeInForce(expiry).
		SetSymbol(optionOrderSymbol)
	if len(orderID) > 0 {
		message.SetOrderID(orderID)
	}

	// FIX 4.3 requires HandlInst.
	if s.Requires(string(fix50sp2.MsgTypeOrdercancelreplacerequest), fix50sp2.TagHandlInst) {
		message.SetHandlInst(fix50sp2.HandlInstAutomatedExecutionOrderPrivateNoBrokerIntervention)
	}

	for _, entry := range partyIDOptions.PartyEntries(s) {
		message.AddNoPartyIDsEntry(entry)
	}

	for _, entry := range attributeOptions.AttributeEntries() {
		message.AddNoOrderAttributesEntry(entry)
	}

	message.SetString(fix50sp2.TagOrderQty, r.quantity.String())
	if ordType != fix50sp2.OrdTypeMarket {
		message.SetString(fix50sp2.TagPrice, r.price.String())
	}

	return message, nil
}

// handler follows the execution reports of the order sent, and replaces
// it at each update.
type handler struct {
	out        io.Writer
	dictionary *dictionary.Dict
	logger     *zerolog.Logger
	session    *config.Session
	send       func(session.Outgoing) error

	// clOrdIDs are those of the order and of the replacements sent.
	clOrdIDs []string
	// acknowledged tells an execution report of the order was received.
	acknowledged bool
	// current is the order as last confirmed, pending the replacement not
	// confirmed yet, if any.
	current replacement
	pending *replacement
	orderID string
	reports int
}

func newHandler(out io.Writer, d *dictionary.Dict, s *config.Session, send func(session.Outgoing) error) *handler {
	return &handler{
		out:        out,
		dictionary: d,
		logger:     config.GetLogger(),
		session:    s,
		send:       send,
		clOrdIDs:   []string{optionOrderID},
		current: replacement{
			clOrdID:  optionOrderID,
			quantity: optionOrderQuantity.Value(),
			price:    optionOrderPrice.Value(),
		},
	}
}

// handle handles a response: it fails on a rejection, a cancellation or an
// OrderCancelReject, and is done once --exec-reports execution reports
// were received, those of pending statuses aside, or with
// --stop-on-final-state a final one. It ignores the messages of other
// orders.
func (h *handler) handle(m *fix.Message) (bool, error) {
	clOrdID := string(m.Get(fix50sp2.TagClOrdID))
	if !slices.Contains(h.clOrdIDs, clOrdID) && !slices.Contains(h.clOrdIDs, string(m.Get(fix50sp2.TagOrigClOrdID))) {
		h.logger.Debug().Msgf("Ignoring message of another order: %s", clOrdID)
		return false, initiator.ErrSkip
	}

	utils.WriteMessageBodyAsTable(h.out, m, h.dictionary)

	switch string(m.MsgType()) {
	case string(fix50sp2.MsgTypeOrdercancelreject):
		return true, options.WithText(errors.ErrFixOrderRejected, m)
	case string(fix50sp2.MsgTypeExecutionreport):
	default:
		return false, nil
	}

	report := fix50sp2.WrapExecutionReport(m)
	ordStatus, ok := report.OrdStatus()
	if !ok {
		return true, fmt.Errorf("%w: missing OrdStatus", errors.ErrFix)
	}

	h.acknowledged = true
	if orderID, ok := report.OrderID(); ok {
		h.orderID = orderID
	}

	switch ordStatus {
	case fix50sp2.OrdStatusRejected:
		return true, options.WithText(errors.ErrFixOrderRejected, m)
	case fix50sp2.OrdStatusCanceled:
		return true, options.WithText(errors.ErrFixOrderCanceled, m)
	case fix50sp2.OrdStatusPendingNew, fix50sp2.OrdStatusPendingReplace, fix50sp2.OrdStatusPendingCancel:
		return false, nil
	}

	if h.pending != nil && clOrdID == h.pending.clOrdID {
		h.current, h.pending = *h.pending, nil
	}

	h.reports++
	if optionExecReports > 0 && h.reports >= optionExecReports {
		return true, nil
	}

	return optionStopOnFinalState && isFinalStatus(ordStatus), nil
}

// update replaces the order, adding --update-order-quantity and
// --update-order-price to its quantity and price, once it was acknowledged
// and its last replacement confirmed.
func (h *handler) update() error {
	if !h.acknowledged || h.pending != nil {
		h.logger.Debug().Msg("Order not acknowledged or replacement pending, update skipped")
		return nil
	}

	r := replacement{
		clOrdID:  uuid.NewString(),
		quantity: h.current.quantity.Add(optionUpdateOrderQuantity.Value()),
		price:    h.current.price.Add(optionUpdateOrderPrice.Value()),
	}

	if err := options.Positive("quantity", r.quantity); err != nil {
		return fmt.Errorf("update: %w", err)
	}

	message, err := buildReplaceMessage(h.session, h.current.clOrdID, h.orderID, r)
	if err != nil {
		return err
	}

	if err := h.send(message); err != nil {
		return err
	}

	h.pending = &r
	h.clOrdIDs = append(h.clOrdIDs, r.clOrdID)

	return nil
}

func isFinalStatus(ordStatus fix50sp2.OrdStatus) bool {
	switch ordStatus {
	case fix50sp2.OrdStatusFilled,
		fix50sp2.OrdStatusDoneForDay,
		fix50sp2.OrdStatusStopped,
		fix50sp2.OrdStatusExpired:
		return true
	default:
		return false
	}
}
