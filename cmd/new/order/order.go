var errInvalidMessageType = fmt.Errorf("invalid message type")

var (
	optionOrderSide, optionOrderType string
	optionOrderSymbol, optionOrderID string
	optionOrderExpiry                string
	optionOrderQuantity              int64
	optionOrderPrice                 float64
	optionOrderOrigination           string
	partyIdOptions                   *options.PartyIdOptions
	attributeOptions                 *options.AttributeOptions
	optionExecReports                int
	optionExecReportsTimeout         time.Duration
	optionExecReportsTimeoutReset    bool
	optionStopOnFinalState           bool
	optionUpdatePeriod               time.Duration
	optionUpdateOrderQuantity        float64
	optionUpdateOrderPrice           float64
)

var NewOrderCmd = &cobra.Command{
	Use:               "order",
	Short:             "New single order",
	Long:              "Send a new single order after initiating a session with a FIX acceptor.",
	Args:              cobra.ExactArgs(0),
	ValidArgsFunction: cobra.NoFileCompletions,
	PersistentPreRunE: utils.MakePersistentPreRunE(Validate),
	RunE:              Execute,
}

func init() {
	NewOrderCmd.Flags().StringVar(&optionOrderID, "id", "", "Order id (uuid autogenerated if not given)")
	NewOrderCmd.Flags().StringVar(&optionOrderSide, "side", "", "Order side (buy, sell ... etc)")
	NewOrderCmd.Flags().StringVar(&optionOrderType, "type", "", "Order type (market, limit, stop ... etc)")
	NewOrderCmd.Flags().StringVar(&optionOrderSymbol, "symbol", "", "Order symbol")
	NewOrderCmd.Flags().Int64Var(&optionOrderQuantity, "quantity", 1, "Order quantity")
	NewOrderCmd.Flags().StringVar(&optionOrderExpiry, "expiry", "day", "Order expiry (day, good_till_cancel ... etc)")
	NewOrderCmd.Flags().Float64Var(&optionOrderPrice, "price", 0.0, "Order price")
	NewOrderCmd.Flags().StringVar(&optionOrderOrigination, "origination", "", "Order origination")

	partyIdOptions = options.NewPartyIdOptions(NewOrderCmd)
	attributeOptions = options.NewAttributeOptions(NewOrderCmd)

	NewOrderCmd.Flags().IntVar(&optionExecReports, "exec-reports", 1, "Expect given number of execution reports before logging out (0 wait indefinitely)")
	NewOrderCmd.Flags().DurationVar(&optionExecReportsTimeout, "exec-reports-timeout", 5*time.Second, "Log out if execution reports not received within timeout (0s wait indefinitely)")
	NewOrderCmd.Flags().BoolVar(&optionExecReportsTimeoutReset, "exec-reports-timeout-reset", false, "Reset execution reports timeout each time an execution report is received")

	NewOrderCmd.Flags().BoolVar(&optionStopOnFinalState, "stop-on-final-state", false, "Stop application when receiving an order with a final state")

	NewOrderCmd.Flags().DurationVar(&optionUpdatePeriod, "update-period", 0, "Period for recurring order price/quantity updates")
	NewOrderCmd.Flags().Float64Var(&optionUpdateOrderQuantity, "update-order-quantity", 0.0, "Update order quantity after each period")
	NewOrderCmd.Flags().Float64Var(&optionUpdateOrderPrice, "update-order-price", 0.0, "Update order price after each period")

	NewOrderCmd.MarkFlagRequired("side")
	NewOrderCmd.MarkFlagRequired("type")
	NewOrderCmd.MarkFlagRequired("symbol")
	NewOrderCmd.MarkFlagRequired("quantity")

	NewOrderCmd.RegisterFlagCompletionFunc("side", complete.OrderSide)
	NewOrderCmd.RegisterFlagCompletionFunc("type", complete.OrderType)
	NewOrderCmd.RegisterFlagCompletionFunc("expiry", complete.OrderTimeInForce)
	NewOrderCmd.RegisterFlagCompletionFunc("symbol", cobra.NoFileCompletions)
	NewOrderCmd.RegisterFlagCompletionFunc("origination", complete.OrderOriginationRole)
}

func Validate(cmd *cobra.Command, args []string) error {
	sides := utils.PrettyOptionValues(dict.OrderSides)
	search := utils.Search(sides, strings.ToLower(optionOrderSide))
	if search < 0 {
		return errors.OptionOrderSideUnknown
	}

	types := utils.PrettyOptionValues(dict.OrderTypes)
	search = utils.Search(types, strings.ToLower(optionOrderType))
	if search < 0 {
		return errors.OptionOrderTypeUnknown
	}

	if len(optionOrderID) == 0 {
		optionOrderID = uuid.NewString()
	}

	if len(optionOrderOrigination) > 0 {
		originations := utils.PrettyOptionValues(dict.OrderOriginations)
		search = utils.Search(originations, strings.ToLower(optionOrderOrigination))
		if search < 0 {
			return errors.OptionOrderOriginationUnknown
		}
	}

	if strings.ToLower(optionOrderType) == "market" && optionOrderPrice > 0 {
		return errors.OptionsInvalidMarketPrice
	} else if strings.ToLower(optionOrderType) != "market" && optionOrderPrice == 0 {
		return errors.OptionsNoPriceGiven
	}

	if err := attributeOptions.Validate(); err != nil {
		return err
	}

	return partyIdOptions.Validate()
}

func Execute(cmd *cobra.Command, args []string) error {
	logger := config.GetLogger()

	c, err := initiator.Connect(cmd.Context(), initiator.Options{
		MsgTypes: []string{
			string(fix50sp2.MsgTypeExecutionreport),
			string(fix50sp2.MsgTypeOrdercancelreject),
			string(fix50sp2.MsgTypeBusinessmessagereject),
		},
	})
	if err != nil {
		return err
	}

	defer c.Close(true)

	session := c.Session

	// Prepare order
	order, err := buildMessage(c.BeginString(), session)
	if err != nil {
		return err
	}

	// Send the order
	if _, err = c.Send(cmd.Context(), order); err != nil {
		return err
	}

	interrupt := make(chan os.Signal, 1)
	signal.Notify(interrupt, os.Interrupt, syscall.SIGTERM)

	execReports := 0
	var waitTimeout <-chan time.Time
	if optionExecReportsTimeout > 0 {
		waitTimeout = time.After(optionExecReportsTimeout)
	} else {
		waitTimeout = make(<-chan time.Time)
	}

	var updatePeriod <-chan time.Time
	if optionUpdatePeriod > 0 {
		updatePeriod = make(<-chan time.Time)
	}

	var lastExecutionReport *fix.Message

LOOP:
	for {
		select {
		case signal := <-interrupt:
			logger.Debug().Msgf("Received signal: %s", signal)
			break LOOP

		case <-waitTimeout:
			logger.Warn().Msgf("Timeout while expecting execution reports (%d/%d)", execReports, optionExecReports)
			break LOOP

		case <-updatePeriod:
			// Prepare order
			orderUpdateMsg, err := buildCancelReplaceMessage(c.BeginString(), session, lastExecutionReport)
			if err != nil {
				return err
			}

			// Send the order
			if _, err = c.Send(cmd.Context(), orderUpdateMsg); err != nil {
				return err
			}

		case <-c.Done():
			break LOOP

		case msg := <-c.Messages():
			if err := processResponse(c, msg); err != nil {
				if errors.Is(err, errInvalidMessageType) {
					continue LOOP
				}

				return err
			}

			if string(msg.MsgType()) == string(fix50sp2.MsgTypeExecutionreport) {
				lastExecutionReport = msg
			}

			if optionStopOnFinalState && isFinalStatus(msg) {
				break LOOP
			}

			// Reset timeout
			if optionExecReportsTimeoutReset && optionExecReportsTimeout > 0 {
				waitTimeout = time.After(optionExecReportsTimeout)
			}

			execReports = execReports + 1
		}

		if optionExecReports != 0 && execReports >= optionExecReports {
			logger.Debug().Msgf("Exiting response loop, execution reports: %d/%d", execReports, optionExecReports)
			break LOOP
		}

		if optionUpdatePeriod > 0 {
			updatePeriod = time.After(optionUpdatePeriod)
		}
	}

	return nil
}

func buildMessage(beginString string, session *config.Session) (*fix50sp2.NewOrderSingleBuilder, error) {
	if !session.IsFIX50SP2() {
		return nil, errors.FixVersionNotImplemented
	}

	eside, err := dict.OrderSideStringToEnum(optionOrderSide)
	if err != nil {
		return nil, err
	}

	etype, err := dict.OrderTypeStringToEnum(optionOrderType)
	if err != nil {
		return nil, err
	}

	eExpiry, err := dict.OrderTimeInForceStringToEnum(optionOrderExpiry)
	if err != nil {
		return nil, err
	}

	// Message
	message := fix50sp2.BuildNewOrderSingle(beginString).
		SetClOrdID(optionOrderID).
		SetSide(eside).
		SetTransactTime(time.Now()).
		SetOrdType(etype).
		SetSymbol(optionOrderSymbol).
		SetTimeInForce(eExpiry)

	for _, entry := range partyIdOptions.PartyEntries(session) {
		message.AddNoPartyIDsEntry(entry)
	}

	for _, entry := range attributeOptions.AttributeEntries() {
		message.AddNoOrderAttributesEntry(entry)
	}

	message.SetString(fix50sp2.TagOrderQty, decimal.NewFromInt(optionOrderQuantity).StringFixed(2))

	if etype != fix50sp2.OrdTypeMarket {
		message.SetString(fix50sp2.TagPrice, decimal.NewFromFloat(optionOrderPrice).StringFixed(2))
	}

	if len(optionOrderOrigination) > 0 {
		message.SetOrderOrigination(dict.OrderOriginations[strings.ToUpper(optionOrderOrigination)])
	}

	return message, nil
}

func buildCancelReplaceMessage(beginString string, session *config.Session, executionReport *fix.Message) (*fix50sp2.OrderCancelReplaceRequestBuilder, error) {
	if executionReport == nil {
		return nil, fmt.Errorf("missing execution report")
	}

	if !session.IsFIX50SP2() {
		return nil, errors.FixVersionNotImplemented
	}

	// Prepare order
	report := fix50sp2.WrapExecutionReport(executionReport)

	orderId, ok := report.OrderID()
	if !ok {
		return nil, fmt.Errorf("execution report: missing OrderID")
	}
	oldClOrdId, ok := report.ClOrdID()
	if !ok {
		return nil, fmt.Errorf("execution report: missing ClOrdID")
	}
	ordType, ok := report.OrdType()
	if !ok {
		return nil, fmt.Errorf("execution report: missing OrdType")
	}
	ordSide, ok := report.Side()
	if !ok {
		return nil, fmt.Errorf("execution report: missing Side")
	}
	eExpiry, err := dict.OrderTimeInForceStringToEnum(optionOrderExpiry)
	if err != nil {
		return nil, err
	}
	totalQty, err := reportDecimal(report.OrderQtyBytes, "OrderQty")
	if err != nil {
		return nil, err
	}
	price, err := reportDecimal(report.PriceBytes, "Price")
	if err != nil {
		return nil, err
	}

	// Message
	message := fix50sp2.BuildOrderCancelReplaceRequest(beginString).
		SetOrderID(orderId).
		SetClOrdID(uuid.NewString()).
		SetOrigClOrdID(oldClOrdId).
		SetSide(ordSide).
		SetTransactTime(time.Now()).
		SetOrdType(ordType).
		SetTimeInForce(eExpiry).
		SetSymbol(optionOrderSymbol)

	for _, entry := range partyIdOptions.PartyEntries(session) {
		message.AddNoPartyIDsEntry(entry)
	}

	message.SetString(fix50sp2.TagOrderQty, totalQty.Add(decimal.NewFromFloat(optionUpdateOrderQuantity)).StringFixed(2))
	message.SetString(fix50sp2.TagPrice, price.Add(decimal.NewFromFloat(optionUpdateOrderPrice)).StringFixed(2))

	return message, nil
}

// reportDecimal reads a decimal field of an execution report from its raw bytes.
func reportDecimal(get func() ([]byte, bool), name string) (decimal.Decimal, error) {
	raw, ok := get()
	if !ok {
		return decimal.Decimal{}, fmt.Errorf("execution report: missing %s", name)
	}

	return decimal.NewFromString(string(raw))
}

func processResponse(c *initiator.Client, msg *fix.Message) error {
	text := string(msg.Get(fix50sp2.TagText))

	makeError := func(errType error) error {
		if len(text) > 0 {
			return fmt.Errorf("%w: %s", errType, text)
		} else {
			return errType
		}
	}

	// MsgType
	switch msgType := string(msg.MsgType()); msgType {
	case string(fixt11.MsgTypeReject),
		string(fix50sp2.MsgTypeBusinessmessagereject),
		string(fix50sp2.MsgTypeOrdercancelreject):
		return makeError(errors.FixOrderRejected)
	case string(fix50sp2.MsgTypeExecutionreport):
	default:
		return errInvalidMessageType
	}

	// OrdStatus
	ordStatus, ok := fix50sp2.WrapExecutionReport(msg).OrdStatus()
	if !ok {
		return fmt.Errorf("missing OrdStatus")
	}

	utils.WriteMessageBodyAsTable(os.Stdout, msg, c.Dictionary)
	switch ordStatus {
	case fix50sp2.OrdStatusNew,
		fix50sp2.OrdStatusPartiallyFilled,
		fix50sp2.OrdStatusFilled,
		fix50sp2.OrdStatusDoneForDay,
		fix50sp2.OrdStatusReplaced,
		fix50sp2.OrdStatusPendingCancel,
		fix50sp2.OrdStatusStopped,
		fix50sp2.OrdStatusSuspended,
		fix50sp2.OrdStatusPendingNew,
		fix50sp2.OrdStatusCalculated,
		fix50sp2.OrdStatusExpired,
		fix50sp2.OrdStatusAcceptedForBidding,
		fix50sp2.OrdStatusPendingReplace:
		return nil
	case fix50sp2.OrdStatusCanceled:
		return makeError(errors.FixOrderCanceled)
	case fix50sp2.OrdStatusRejected:
		return makeError(errors.FixOrderRejected)
	default:
		return makeError(errors.FixOrderStatusUnknown)
	}
}

func isFinalStatus(msg *fix.Message) bool {
	ordStatus, ok := fix50sp2.WrapExecutionReport(msg).OrdStatus()
	if !ok {
		return false
	}

	switch ordStatus {
	case fix50sp2.OrdStatusFilled,
		fix50sp2.OrdStatusDoneForDay,
		fix50sp2.OrdStatusStopped,
		fix50sp2.OrdStatusExpired,
		fix50sp2.OrdStatusCanceled,
		fix50sp2.OrdStatusRejected:
		return true
	default:
		return false
	}
}
