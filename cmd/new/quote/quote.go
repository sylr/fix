var (
	optionSymbol, optionQuoteID               string
	optionBuyQuantities, optionSellQuantities options.Decimals
	optionBuyPrices, optionSellPrices         options.Decimals
	optionAutoPriceUpdate                     bool
	partyIDOptions                            *options.PartyIDOptions
	optionExecReports                         int
	optionExecReportsTimeout                  time.Duration
	optionExecReportsTimeoutReset             bool
	optionStopOnFinalState                    bool
	optionUpdateQuotePeriod                   time.Duration
	optionCancelAfterUpdates                  bool
	optionCancelAfterXUpdates                 int
)

var NewQuoteCmd = &cobra.Command{
	Use:               "quote",
	Short:             "New quote",
	Long:              "Send a new quote after initiating a session with a FIX acceptor.",
	Args:              cobra.ExactArgs(0),
	ValidArgsFunction: cobra.NoFileCompletions,
	PersistentPreRunE: Validate,
	RunE:              Execute,
}

func init() {
	flags := NewQuoteCmd.Flags()
	flags.StringVar(&optionQuoteID, "id", "", "Quote id, of the quote and its updates (uuid autogenerated if not given)")
	flags.StringVar(&optionSymbol, "symbol", "", "Quote symbol")
	flags.Var(&optionBuyQuantities, "buy-quantities", "Quote buy quantities, one per buy price")
	flags.Var(&optionSellQuantities, "sell-quantities", "Quote sell quantities, one per sell price")
	flags.Var(&optionBuyPrices, "buy-prices", "Quote buy prices, one per quote update")
	flags.Var(&optionSellPrices, "sell-prices", "Quote sell prices, one per quote update")
	flags.BoolVar(&optionAutoPriceUpdate, "auto-price-update", false, "Generate price oscillation to send an infinity of quote updates")

	partyIDOptions = options.NewPartyIDOptions(NewQuoteCmd)

	flags.IntVar(&optionExecReports, "exec-reports", 1, "Expect given number of quote status or execution reports before logging out (0 wait until interrupted)")
	flags.DurationVar(&optionExecReportsTimeout, "exec-reports-timeout", 5*time.Second, "Fail if the reports are not received within timeout, or the first one with --exec-reports 0 (0s wait indefinitely)")
	flags.BoolVar(&optionExecReportsTimeoutReset, "exec-reports-timeout-reset", false, "Reset reports timeout each time a report is received")

	flags.BoolVar(&optionStopOnFinalState, "stop-on-final-state", false, "Stop when the quote, or an order it filled, reaches a final state")

	flags.DurationVar(&optionUpdateQuotePeriod, "update-period", 10*time.Second, "Period for recurring quote updates (0s for none)")
	flags.BoolVar(&optionCancelAfterUpdates, "cancel-quote-after-updates", false, "Cancel quote when all updates are done")
	flags.IntVar(&optionCancelAfterXUpdates, "cancel-quote-after-x-updates", -1, "Cancel quote after X updates")

	options.Must(NewQuoteCmd.MarkFlagRequired("symbol"))

	options.Must(NewQuoteCmd.RegisterFlagCompletionFunc("symbol", cobra.NoFileCompletions))
}

// Validate checks the options, then that the quote fits the session, before
// connecting.
func Validate(cmd *cobra.Command, args []string) error {
	if err := validateOptions(); err != nil {
		return err
	}

	s, err := config.CurrentSession()
	if err != nil {
		return err
	}

	quote, err := buildMessage(s, 0, uuid.NewString())
	if err != nil {
		return err
	}
	if err := s.Check(quote); err != nil {
		return err
	}

	cancel, err := buildCancelMessage(s, uuid.NewString())
	if err != nil {
		return err
	}

	return s.Check(cancel)
}

func validateOptions() error {
	if len(optionSymbol) == 0 {
		return errors.ErrOptionsNoSymbolGiven
	}

	if len(optionBuyPrices) != len(optionBuyQuantities) {
		return fmt.Errorf("%w: number of buy prices (%d) must be equal to buy quantities (%d)", errors.ErrOptionsInconsistentValues, len(optionBuyPrices), len(optionBuyQuantities))
	}

	if len(optionSellPrices) != len(optionSellQuantities) {
		return fmt.Errorf("%w: number of sell prices (%d) must be equal to sell quantities (%d)", errors.ErrOptionsInconsistentValues, len(optionSellPrices), len(optionSellQuantities))
	}

	if optionAutoPriceUpdate && (len(optionBuyPrices) > 1 || len(optionSellPrices) > 1) {
		return fmt.Errorf("%w: --auto-price-update works with only 1 price per side", errors.ErrOptions)
	}

	for name, values := range map[string]options.Decimals{
		"buy-quantities":  optionBuyQuantities,
		"sell-quantities": optionSellQuantities,
	} {
		for _, v := range values {
			if err := options.Positive(name, v); err != nil {
				return err
			}
		}
	}

	if len(optionQuoteID) == 0 {
		optionQuoteID = uuid.NewString()
	}

	return partyIDOptions.Validate()
}

func Execute(cmd *cobra.Command, args []string) error {
	ctx := cmd.Context()

	c, err := initiator.Connect(ctx, initiator.Options{
		MsgTypes: []string{
			string(fix50sp2.MsgTypeExecutionreport),
			string(fix50sp2.MsgTypeQuotestatusreport),
		},
	})
	if err != nil {
		return err
	}
	defer c.Close(true)

	q := newQuoter(cmd.OutOrStdout(), c.Dictionary, c.Session, func(m session.Outgoing) error {
		_, err := c.Send(ctx, m)
		return err
	})

	if err := q.quote(); err != nil {
		return err
	}

	opts := initiator.AwaitOptions{What: "quote reports", Timeout: optionExecReportsTimeout}
	switch {
	case optionExecReportsTimeoutReset:
		opts.Mode = initiator.TimeoutIdle
	case optionExecReports == 0:
		opts.Mode = initiator.TimeoutFirst
	}

	if optionUpdateQuotePeriod > 0 {
		ticker := time.NewTicker(optionUpdateQuotePeriod)
		defer ticker.Stop()
		opts.Tick, opts.OnTick = ticker.C, q.update
	}

	return c.Await(ctx, opts, q.handle)
}

// buildMessage builds the Quote of update iteration, 0 for the first,
// with QuoteMsgID quoteMsgID if the session's FIX version defines it.
func buildMessage(s *config.Session, iteration int, quoteMsgID string) (*fix50sp2.QuoteBuilder, error) {
	if err := s.CheckSupported(); err != nil {
		return nil, err
	}

	message := fix50sp2.BuildQuote(s.BeginString).
		SetQuoteID(optionQuoteID).
		SetTransactTime(time.Now()).
		SetSymbol(optionSymbol)

	// FIX 4.3 and 4.4 do not define QuoteMsgID.
	if s.Defines(string(fix50sp2.MsgTypeQuote), fix50sp2.TagQuoteMsgID) {
		message.SetQuoteMsgID(quoteMsgID)
	}

	for _, entry := range partyIDOptions.PartyEntries(s) {
		message.AddNoPartyIDsEntry(entry)
	}

	if optionAutoPriceUpdate {
		adjustment := decimal.New(int64(iteration%100), -2)
		if len(optionBuyPrices) == 1 {
			price := optionBuyPrices[0].Sub(adjustment)
			setQuoteSide(message, fix50sp2.TagBidSize, fix50sp2.TagBidPx, optionBuyQuantities[0], price)
		}
		if len(optionSellPrices) == 1 {
			setQuoteSide(message, fix50sp2.TagOfferSize, fix50sp2.TagOfferPx, optionSellQuantities[0], optionSellPrices[0].Add(adjustment))
		}
	} else {
		if iteration < len(optionBuyPrices) {
			setQuoteSide(message, fix50sp2.TagBidSize, fix50sp2.TagBidPx, optionBuyQuantities[iteration], optionBuyPrices[iteration])
		}
		if iteration < len(optionSellPrices) {
			setQuoteSide(message, fix50sp2.TagOfferSize, fix50sp2.TagOfferPx, optionSellQuantities[iteration], optionSellPrices[iteration])
		}
	}

	return message, nil
}

// setQuoteSide writes the size and price of one side of a quote as given.
func setQuoteSide(message *fix50sp2.QuoteBuilder, sizeTag, pxTag int, size, price decimal.Decimal) {
	message.SetString(sizeTag, size.String())
	message.SetString(pxTag, price.String())
}

// buildCancelMessage builds the QuoteCancel of the quote, with QuoteMsgID
// quoteMsgID if the session's FIX version defines it.
func buildCancelMessage(s *config.Session, quoteMsgID string) (*fix50sp2.QuoteCancelBuilder, error) {
	if err := s.CheckSupported(); err != nil {
		return nil, err
	}

	message := fix50sp2.BuildQuoteCancel(s.BeginString).
		SetQuoteID(optionQuoteID)

	// FIX 4.3 and 4.4 do not define QuoteMsgID in a QuoteCancel.
	if s.Defines(string(fix50sp2.MsgTypeQuotecancel), fix50sp2.TagQuoteMsgID) {
		message.SetQuoteMsgID(quoteMsgID)
	}

	message.SetQuoteCancelType(fix50sp2.QuoteCancelTypeCancelForOneOrMoreSecurities).
		AddNoQuoteEntriesEntry(fix50sp2.NewNoQuoteEntriesEntry().SetSymbol(optionSymbol))

	for _, entry := range partyIDOptions.PartyEntries(s) {
		message.AddNoPartyIDsEntry(entry)
	}

	return message, nil
}

// quoter sends the quote, its updates and its cancellation, and follows
// the reports of them.
type quoter struct {
	out        io.Writer
	dictionary *dictionary.Dict
	logger     *zerolog.Logger
	session    *config.Session
	send       func(session.Outgoing) error

	// iteration counts the quotes sent; updating tells updates remain.
	iteration int
	updating  bool
	// quoteMsgIDs are those of the messages sent; quoteRespIDs those of
	// the QuoteResponses to the quote its reports told.
	quoteMsgIDs  []string
	quoteRespIDs []string
	reports      int
}

func newQuoter(out io.Writer, d *dictionary.Dict, s *config.Session, send func(session.Outgoing) error) *quoter {
	return &quoter{out: out, dictionary: d, logger: config.GetLogger(), session: s, send: send, updating: true}
}

// quote sends the quote of the current iteration.
func (q *quoter) quote() error {
	quoteMsgID := uuid.NewString()
	message, err := buildMessage(q.session, q.iteration, quoteMsgID)
	if err != nil {
		return err
	}

	if err := q.send(message); err != nil {
		return err
	}
	q.iteration++
	q.quoteMsgIDs = append(q.quoteMsgIDs, quoteMsgID)

	return nil
}

// cancel sends the QuoteCancel of the quote.
func (q *quoter) cancel() error {
	quoteMsgID := uuid.NewString()
	message, err := buildCancelMessage(q.session, quoteMsgID)
	if err != nil {
		return err
	}

	if err := q.send(message); err != nil {
		return err
	}
	q.quoteMsgIDs = append(q.quoteMsgIDs, quoteMsgID)

	return nil
}

// update sends the next update of the quote, preceded by its cancellation
// every --cancel-quote-after-x-updates, or once the prices given are all
// sent, its cancellation if --cancel-quote-after-updates.
func (q *quoter) update() error {
	if !q.updating {
		return nil
	}

	if !optionAutoPriceUpdate && q.iteration >= len(optionBuyPrices) && q.iteration >= len(optionSellPrices) {
		q.updating = false
		if optionCancelAfterUpdates {
			return q.cancel()
		}
		return nil
	}

	if optionCancelAfterXUpdates > 0 && q.iteration%optionCancelAfterXUpdates == 0 {
		if err := q.cancel(); err != nil {
			return err
		}
	}

	return q.quote()
}

// handle handles a report of the quote: it fails on a rejection, a quote
// not found included, and is done once --exec-reports reports were
// received, or with --stop-on-final-state a final one. It ignores the
// reports of other quotes and those it cannot tie to the quote.
func (q *quoter) handle(m *fix.Message) (bool, error) {
	if !q.matches(m) {
		q.logger.Debug().Msgf("Ignoring %s message of another quote", m.MsgType())
		return false, initiator.ErrSkip
	}

	if id := m.Get(fix50sp2.TagQuoteRespID); id != nil && !slices.Contains(q.quoteRespIDs, string(id)) {
		q.quoteRespIDs = append(q.quoteRespIDs, string(id))
	}

	utils.WriteMessageBodyAsTable(q.out, m, q.dictionary)

	var final bool
	switch string(m.MsgType()) {
	case string(fix50sp2.MsgTypeQuotestatusreport):
		status, ok := fix50sp2.WrapQuoteStatusReport(m).QuoteStatus()
		if status == fix50sp2.QuoteStatusRejected || m.Get(fix50sp2.TagQuoteRejectReason) != nil {
			return true, options.WithText(errors.ErrFixQuoteRejected, m)
		}
		if status == fix50sp2.QuoteStatusQuoteNotFound {
			return true, options.WithText(fmt.Errorf("%w: quote not found", errors.ErrFixQuoteRejected), m)
		}
		final = ok && isFinalQuoteStatus(status)

	case string(fix50sp2.MsgTypeExecutionreport):
		ordStatus, ok := fix50sp2.WrapExecutionReport(m).OrdStatus()
		if !ok {
			return true, fmt.Errorf("%w: missing OrdStatus", errors.ErrFix)
		}
		if ordStatus == fix50sp2.OrdStatusRejected {
			return true, options.WithText(errors.ErrFixOrderRejected, m)
		}
		final = isFinalStatus(ordStatus)
	}

	q.reports++
	if optionExecReports > 0 && q.reports >= optionExecReports {
		return true, nil
	}

	return optionStopOnFinalState && final, nil
}

// matches reports whether m is a report of the quote: by its QuoteMsgID
// (FIX 5.0SP2), or else a QuoteStatusReport by its QuoteID and an
// ExecutionReport by its QuoteRespID (FIX 4.4 on) if a report of the quote
// told it. FIX 4.3 ExecutionReports tie to no quote.
func (q *quoter) matches(m *fix.Message) bool {
	if id := m.Get(fix50sp2.TagQuoteMsgID); id != nil {
		return slices.Contains(q.quoteMsgIDs, string(id))
	}

	if string(m.MsgType()) == string(fix50sp2.MsgTypeQuotestatusreport) {
		return string(m.Get(fix50sp2.TagQuoteID)) == optionQuoteID
	}

	id := m.Get(fix50sp2.TagQuoteRespID)

	return id != nil && slices.Contains(q.quoteRespIDs, string(id))
}

func isFinalStatus(ordStatus fix50sp2.OrdStatus) bool {
	switch ordStatus {
	case fix50sp2.OrdStatusFilled,
		fix50sp2.OrdStatusDoneForDay,
		fix50sp2.OrdStatusStopped,
		fix50sp2.OrdStatusExpired,
		fix50sp2.OrdStatusCanceled:
		return true
	default:
		return false
	}
}

func isFinalQuoteStatus(status fix50sp2.QuoteStatus) bool {
	switch status {
	case fix50sp2.QuoteStatusCanceled,
		fix50sp2.QuoteStatusCanceledAll,
		fix50sp2.QuoteStatusCanceledForSpecificSecurities,
		fix50sp2.QuoteStatusCanceledForSpecificSecuritytypes,
		fix50sp2.QuoteStatusCanceledForUnderlying,
		fix50sp2.QuoteStatusCanceledDueToLockedMarket,
		fix50sp2.QuoteStatusCanceledDueToCrossedMarket,
		fix50sp2.QuoteStatusRemovedFromMarket,
		fix50sp2.QuoteStatusExpired,
		fix50sp2.QuoteStatusTradedAndRemoved:
		return true
	default:
		return false
	}
}
