var (
	optionOrderSide, optionOrderType string
	optionOrderSymbol                string
	optionClOrdID                    string
	optionOrderID, optionOrigClOrdID string
	optionOrderExpiry                string
	optionOrderQuantity              options.Decimal
	optionOrderPrice                 options.Decimal
	partyIDOptions                   *options.PartyIDOptions
	attributeOptions                 *options.AttributeOptions
	optionExecReports                int
	optionExecReportsTimeout         time.Duration
	optionExecReportsTimeoutReset    bool
	optionStopOnFinalState           bool
)

var AmendOrderCmd = &cobra.Command{
	Use:               "order",
	Short:             "Amend single order",
	Long:              "Send an order cancel/replace request after initiating a session with a FIX acceptor.",
	Args:              cobra.ExactArgs(0),
	ValidArgsFunction: cobra.NoFileCompletions,
	PersistentPreRunE: Validate,
	RunE:              Execute,
}

func init() {
	flags := AmendOrderCmd.Flags()
	flags.StringVar(&optionOrderID, "id", "", "Order id (required if origclordid empty)")
	flags.StringVar(&optionOrigClOrdID, "origclordid", "", "Client order id of the order to amend (required if id empty, and by FIX 4.x)")
	flags.StringVar(&optionClOrdID, "clordid", "", "Client order id of the amendment (uuid autogenerated if not given)")
	flags.StringVar(&optionOrderSide, "side", "", "Order side (buy, sell ... etc)")
	flags.StringVar(&optionOrderType, "type", "", "Order type (market, limit, stop ... etc)")
	flags.StringVar(&optionOrderSymbol, "symbol", "", "Order symbol")
	flags.Var(&optionOrderQuantity, "quantity", "Order quantity")
	flags.StringVar(&optionOrderExpiry, "expiry", "day", "Order expiry (day, good_till_cancel ... etc)")
	flags.Var(&optionOrderPrice, "price", "Order price (not for market orders)")

	partyIDOptions = options.NewPartyIDOptions(AmendOrderCmd)
	attributeOptions = options.NewAttributeOptions(AmendOrderCmd)

	flags.IntVar(&optionExecReports, "exec-reports", 1, "Expect given number of execution reports, pending ones aside, before logging out (0 wait until interrupted)")
	flags.DurationVar(&optionExecReportsTimeout, "exec-reports-timeout", 5*time.Second, "Fail if the execution reports are not received within timeout, or the first one with --exec-reports 0 (0s wait indefinitely)")
	flags.BoolVar(&optionExecReportsTimeoutReset, "exec-reports-timeout-reset", false, "Reset execution reports timeout each time an execution report is received")

	flags.BoolVar(&optionStopOnFinalState, "stop-on-final-state", false, "Stop when the order reaches a final state")

	options.Must(AmendOrderCmd.MarkFlagRequired("side"))
	options.Must(AmendOrderCmd.MarkFlagRequired("type"))
	options.Must(AmendOrderCmd.MarkFlagRequired("symbol"))
	options.Must(AmendOrderCmd.MarkFlagRequired("quantity"))

	options.Must(AmendOrderCmd.RegisterFlagCompletionFunc("side", complete.OrderSide))
	options.Must(AmendOrderCmd.RegisterFlagCompletionFunc("type", complete.OrderType))
	options.Must(AmendOrderCmd.RegisterFlagCompletionFunc("expiry", complete.OrderTimeInForce))
	options.Must(AmendOrderCmd.RegisterFlagCompletionFunc("symbol", cobra.NoFileCompletions))
}

// Validate checks the options, then that the amendment fits the session,
// before connecting.
func Validate(cmd *cobra.Command, args []string) error {
	if err := validateOptions(); err != nil {
		return err
	}

	s, err := config.CurrentSession()
	if err != nil {
		return err
	}

	amendment, err := buildMessage(s)
	if err != nil {
		return err
	}

	return s.Check(amendment)
}

func validateOptions() error {
	if _, err := options.Side(optionOrderSide); err != nil {
		return err
	}

	ordType, err := options.OrdType(optionOrderType)
	if err != nil {
		return err
	}

	if _, err := options.TimeInForce(optionOrderExpiry); err != nil {
		return err
	}

	if len(optionOrderSymbol) == 0 {
		return errors.ErrOptionsNoSymbolGiven
	}

	if len(optionOrderID) == 0 && len(optionOrigClOrdID) == 0 {
		return fmt.Errorf("%w: --id or --origclordid required", errors.ErrOptions)
	}

	if err := options.Positive("quantity", optionOrderQuantity.Value()); err != nil {
		return err
	}

	if err := options.CheckPrice(ordType, optionOrderPrice); err != nil {
		return err
	}

	if len(optionClOrdID) == 0 {
		optionClOrdID = uuid.NewString()
	}

	if err := attributeOptions.Validate(); err != nil {
		return err
	}

	return partyIDOptions.Validate()
}

func Execute(cmd *cobra.Command, args []string) error {
	ctx := cmd.Context()

	c, err := initiator.Connect(ctx, initiator.Options{
		MsgTypes: []string{
			string(fix50sp2.MsgTypeExecutionreport),
			string(fix50sp2.MsgTypeOrdercancelreject),
		},
	})
	if err != nil {
		return err
	}
	defer c.Close(true)

	amendment, err := buildMessage(c.Session)
	if err != nil {
		return err
	}

	if _, err := c.Send(ctx, amendment); err != nil {
		return err
	}

	opts := initiator.AwaitOptions{What: "execution reports", Timeout: optionExecReportsTimeout}
	switch {
	case optionExecReportsTimeoutReset:
		opts.Mode = initiator.TimeoutIdle
	case optionExecReports == 0:
		opts.Mode = initiator.TimeoutFirst
	}

	h := &handler{out: cmd.OutOrStdout(), dictionary: c.Dictionary, logger: config.GetLogger()}

	return c.Await(ctx, opts, h.handle)
}

func buildMessage(s *config.Session) (*fix50sp2.OrderCancelReplaceRequestBuilder, error) {
	if err := s.CheckSupported(); err != nil {
		return nil, err
	}

	// FIX 4.3 and 4.4 require OrigClOrdID.
	if len(optionOrigClOrdID) == 0 && s.Requires(string(fix50sp2.MsgTypeOrdercancelreplacerequest), fix50sp2.TagOrigClOrdID) {
		return nil, fmt.Errorf("%w: %s requires --origclordid", errors.ErrOptions, s.Version())
	}

	side, err := options.Side(optionOrderSide)
	if err != nil {
		return nil, err
	}

	ordType, err := options.OrdType(optionOrderType)
	if err != nil {
		return nil, err
	}

	expiry, err := options.TimeInForce(optionOrderExpiry)
	if err != nil {
		return nil, err
	}

	message := fix50sp2.BuildOrderCancelReplaceRequest(s.BeginString)
	if len(optionOrderID) > 0 {
		message.SetOrderID(optionOrderID)
	}
	if len(optionOrigClOrdID) > 0 {
		message.SetOrigClOrdID(optionOrigClOrdID)
	}
	message.SetClOrdID(optionClOrdID).
		SetSide(side).
		SetTransactTime(time.Now()).
		SetOrdType(ordType).
		SetTimeInForce(expiry).
		SetSymbol(optionOrderSymbol)

	// FIX 4.3 requires HandlInst.
	if s.Requires(string(fix50sp2.MsgTypeOrdercancelreplacerequest), fix50sp2.TagHandlInst) {
		message.SetHandlInst(fix50sp2.HandlInstAutomatedExecutionOrderPrivateNoBrokerIntervention)
	}

	for _, entry := range partyIDOptions.PartyEntries(s) {
		message.AddNoPartyIDsEntry(entry)
	}

	for _, entry := range attributeOptions.AttributeEntries() {
		message.AddNoOrderAttributesEntry(entry)
	}

	message.SetString(fix50sp2.TagOrderQty, optionOrderQuantity.Value().String())
	if ordType != fix50sp2.OrdTypeMarket {
		message.SetString(fix50sp2.TagPrice, optionOrderPrice.Value().String())
	}

	return message, nil
}

// handler follows the responses to the amendment, those whose ClOrdID or
// OrigClOrdID is the amendment's.
type handler struct {
	out        io.Writer
	dictionary *dictionary.Dict
	logger     *zerolog.Logger
	reports    int
}

// handle handles a response: it fails on a rejection, a cancellation or an
// OrderCancelReject, and is done once --exec-reports execution reports
// were received, those of pending statuses aside, or with
// --stop-on-final-state a final one.
func (h *handler) handle(m *fix.Message) (bool, error) {
	clOrdID := string(m.Get(fix50sp2.TagClOrdID))
	if clOrdID != optionClOrdID && string(m.Get(fix50sp2.TagOrigClOrdID)) != optionClOrdID {
		h.logger.Debug().Msgf("Ignoring message of another order: %s", clOrdID)
		return false, initiator.ErrSkip
	}

	utils.WriteMessageBodyAsTable(h.out, m, h.dictionary)

	if string(m.MsgType()) == string(fix50sp2.MsgTypeOrdercancelreject) {
		return true, options.WithText(errors.ErrFixOrderRejected, m)
	}

	ordStatus, ok := fix50sp2.WrapExecutionReport(m).OrdStatus()
	if !ok {
		return true, fmt.Errorf("%w: missing OrdStatus", errors.ErrFix)
	}

	switch ordStatus {
	case fix50sp2.OrdStatusRejected:
		return true, options.WithText(errors.ErrFixOrderRejected, m)
	case fix50sp2.OrdStatusCanceled:
		return true, options.WithText(errors.ErrFixOrderCanceled, m)
	case fix50sp2.OrdStatusPendingNew, fix50sp2.OrdStatusPendingReplace, fix50sp2.OrdStatusPendingCancel:
		return false, nil
	}

	h.reports++
	if optionExecReports > 0 && h.reports >= optionExecReports {
		return true, nil
	}

	return optionStopOnFinalState && isFinalStatus(ordStatus), nil
}

func isFinalStatus(ordStatus fix50sp2.OrdStatus) bool {
	switch ordStatus {
	case fix50sp2.OrdStatusFilled,
		fix50sp2.OrdStatusDoneForDay,
		fix50sp2.OrdStatusStopped,
		fix50sp2.OrdStatusExpired:
		return true
	default:
		return false
	}
}
