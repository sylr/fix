package listsecurity

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/google/uuid"
	"github.com/spf13/cobra"
	"github.com/sylr/fix2/fix"
	"github.com/sylr/fix2/fix/session"

	"sylr.dev/fix/v2/cli/complete"
	"sylr.dev/fix/v2/config"
	"sylr.dev/fix/v2/dict"
	"sylr.dev/fix/v2/errors"
	"sylr.dev/fix/v2/fix50sp2"
	"sylr.dev/fix/v2/initiator"
	"sylr.dev/fix/v2/utils"
)

var (
	optionType          string
	optionSymbol        string
	optionSecurityReqID string
)

var ListSecurityCmd = &cobra.Command{
	Use:     "security",
	Aliases: []string{"securities"},
	Short:   "List securities",
	Long: "Send a SecurityListRequest after initiating a session with a FIX acceptor, and print the " +
		"SecurityList answering it, every fragment of it.",
	Args:              cobra.ExactArgs(0),
	ValidArgsFunction: cobra.NoFileCompletions,
	PersistentPreRunE: utils.MakePersistentPreRunE(Validate),
	RunE:              Execute,
}

func init() {
	ListSecurityCmd.Flags().StringVar(&optionType, "type", "all_securities", "Request type (all_securities, symbol, product ... etc)")
	ListSecurityCmd.Flags().StringVar(&optionSymbol, "symbol", "", "Symbol, for --type symbol")
	ListSecurityCmd.Flags().StringVar(&optionSecurityReqID, "request-id", "", "SecurityReqID (uuid autogenerated if not given)")

	if err := ListSecurityCmd.RegisterFlagCompletionFunc("type", complete.SecurityListRequestType); err != nil {
		panic(err)
	}
	if err := ListSecurityCmd.RegisterFlagCompletionFunc("symbol", cobra.NoFileCompletions); err != nil {
		panic(err)
	}
}

func Validate(cmd *cobra.Command, args []string) error {
	requestType, ok := dict.SecurityListRequestTypes[strings.ToUpper(optionType)]
	if !ok {
		return fmt.Errorf("%w: unknown request type `%s`", errors.ErrOptions, optionType)
	}

	switch bySymbol := requestType == fix50sp2.SecurityListRequestTypeSymbol; {
	case bySymbol && len(optionSymbol) == 0:
		return fmt.Errorf("%w: --type symbol needs a --symbol", errors.ErrOptions)
	case !bySymbol && len(optionSymbol) > 0:
		return fmt.Errorf("%w: --symbol goes with --type symbol", errors.ErrOptions)
	}

	if len(optionSecurityReqID) == 0 {
		optionSecurityReqID = uuid.NewString()
	}

	return nil
}

func Execute(cmd *cobra.Command, args []string) error {
	ctx := cmd.Context()

	s, err := config.CurrentSession()
	if err != nil {
		return err
	}

	request, err := buildMessage(s)
	if err != nil {
		return err
	}

	c, err := initiator.Connect(ctx, initiator.Options{
		MsgTypes: []string{string(fix50sp2.MsgTypeSecuritylist)},
	})
	if err != nil {
		return err
	}
	defer c.Close(true)

	if _, err := c.Send(ctx, request); err != nil {
		return err
	}

	// The list may come in fragments, the timeout bounding the wait for
	// each.
	listed := 0
	opts := initiator.AwaitOptions{What: "security list", Timeout: config.Timeout(0), Mode: initiator.TimeoutIdle}

	return c.Await(ctx, opts, func(m *fix.Message) (bool, error) {
		if id := string(m.Get(fix50sp2.TagSecurityReqID)); id != optionSecurityReqID {
			config.GetLogger().Info().Msgf("Ignoring the security list of another request: %q", id)
			return false, initiator.ErrSkip
		}

		utils.WriteMessageBodyAsTable(cmd.OutOrStdout(), m, c.Dictionary)

		if result := string(m.Get(fix50sp2.TagSecurityRequestResult)); result != "" && result != string(fix50sp2.SecurityRequestResultValidRequest) {
			return true, fmt.Errorf("%w: security list request result %s", errors.ErrFixRejected, dict.EnumName(c.Dictionary, fix50sp2.TagSecurityRequestResult, result))
		}

		return lastFragment(m, &listed), nil
	})
}

// lastFragment reports whether m is the last fragment of a SecurityList:
// it says so, or the securities listed so far, which it adds its own to,
// reach the total it tells. A list telling neither is not fragmented.
func lastFragment(m *fix.Message, listed *int) bool {
	n, _ := strconv.Atoi(string(m.Get(fix50sp2.TagNoRelatedSym)))
	*listed += n

	if last := m.Get(fix50sp2.TagLastFragment); last != nil {
		return string(last) == string(fix50sp2.LastFragmentYes)
	}

	if total, err := strconv.Atoi(string(m.Get(fix50sp2.TagTotNoRelatedSym))); err == nil {
		return *listed >= total
	}

	return true
}

// buildMessage builds the SecurityListRequest for session s.
func buildMessage(s *config.Session) (session.Outgoing, error) {
	if err := s.CheckSupported(); err != nil {
		return nil, err
	}

	message := fix50sp2.BuildSecurityListRequest(s.BeginString).
		SetSecurityReqID(optionSecurityReqID).
		SetSecurityListRequestType(dict.SecurityListRequestTypes[strings.ToUpper(optionType)])

	if len(optionSymbol) > 0 {
		message.SetSymbol(optionSymbol)
	}

	return message, nil
}
